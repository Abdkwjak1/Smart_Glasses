"""Regenerate the recorded Arabic prompts with Google TTS (needs network).

Only the intro prompt is regenerated by default; pass --objects to rebuild every object
sound (translates the COCO class list with the optional `googletrans` package).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from smart_glasses.audio import synthesize  # noqa: E402

AUDIO = ROOT / "assets" / "audio"
INTRO = (
    "مرحباً بك في النظارة الذكية، قل كلمة أغراض للتعرف على الاغراض، "
    "قل كلمة أشخاص للتعرف على الأشخاص، قل كلمة نصوص للتعرف على النصوص، "
    "قل الرقم صفر للخروج"
)


def main() -> None:
    synthesize(INTRO, AUDIO / "commands" / "intro.mp3")
    if "--objects" in sys.argv:
        import googletrans

        translator = googletrans.Translator()
        for name in (AUDIO.parent / "coco_classes.txt").read_text().splitlines():
            if name.strip():
                text = translator.translate(name.strip(), dest="ar").text
                synthesize(text, AUDIO / "objects" / f"{name.strip()}.mp3")


if __name__ == "__main__":
    main()
